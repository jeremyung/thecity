"""Blender-authored metre-scale components -> renderer-neutral triangle library."""
import bpy,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3]
bpy.ops.object.select_all(action='SELECT');bpy.ops.object.delete(use_global=False)
parts={}
def box(name,xyz,size,material):
 bpy.ops.mesh.primitive_cube_add(size=1,location=xyz);o=bpy.context.object;o.name=name;o.dimensions=size
 bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
 mod=o.modifiers.new('small edge highlights','BEVEL');mod.width=.012;mod.segments=1
 bpy.context.view_layer.objects.active=o;bpy.ops.object.modifier_apply(modifier=mod.name)
 mesh=o.data;mesh.calc_loop_triangles();p=[];n=[];uv=[]
 for tri in mesh.loop_triangles:
  for vi in tri.vertices:
   point=o.matrix_world@mesh.vertices[vi].co;normal=tri.normal
   p.extend(round(v,6) for v in (point.x,point.z,-point.y));n.extend(round(v,6) for v in (normal.x,normal.z,-normal.y));uv.extend((point.x*2.5,point.z*2.5))
 parts.setdefault(current,[]).append({'material':material,'positions':p,'normals':n,'uvs':uv})
for current,width in [('window',1.3),('balcony-door',1.8),('entrance',1.6)]:
 h=1.5 if current=='window' else 2.2
 box('glazing',(0,0,0),(width,.045,h),'glass')
 for x in (-width/2,0,width/2):box('jamb',(x,-.065,0),(.055,.13,h+.1),'metal')
 for z in (-h/2,h/2):box('rail',(0,-.065,z),(width+.1,.13,.055),'metal')
 if current!='window':
  box('shutter housing',(0,-.06,h/2+.13),(width+.18,.25,.16),'concrete')
  for x in (-width/2+.05,width/2-.05):box('door track',(x,-.11,0),(.025,.035,h),'metal')
  box('handle',(.07,-.15,-.18),(.025,.04,.18),'metal')
 if current=='window':box('sill',(0,-.14,-h/2-.065),(width+.24,.35,.1),'concrete')
current='balcony'
box('slab',(0,-.44,0),(1.8,.94,.14),'concrete')
box('handrail',(0,-.88,1.08),(1.8,.055,.055),'metal')
for i in range(11):box('baluster',(-.87+i*.174,-.88,.58),(.025,.025,1),'metal')
for x in (-.87,.87):
 box('privacy screen',(x,-.44,.66),(.055,.85,1.2),'concrete')
current='ac'
box('unit',(0,0,0),(.8,.4,.55),'concrete')
for i in range(6):box('grille',(-.3+i*.12,-.21,0),(.025,.025,.4),'metal')
current='mailboxes'
for row in range(3):
 for col in range(2):
  x=(col-.5)*.23;z=(row-1)*.16
  box('mailbox',(x,0,z),(.21,.09,.14),'metal')
  box('label slot',(x,-.05,z+.025),(.13,.01,.018),'concrete')
current='meter-bank'
box('utility cabinet',(0,0,0),(.42,.16,.72),'concrete')
for z in (-.19,.04,.25):box('meter face',(0,-.09,z),(.2,.025,.12),'metal')
current='laundry-bracket'
for x in (-.5,.5):
 box('bracket',(x,-.12,0),(.035,.3,.035),'metal')
box('drying pole',(0,-.25,0),(1.15,.025,.025),'metal')
text='// Generated by art-workshop/architecture-pilot/runtime-components/build.py; metres, Y up, +Z outward.\nexport const apartmentComponents = '+json.dumps(parts,separators=(',',':'))+' as const;\n'
(ROOT/'web/src/render/generated/apartment-components.ts').write_text(text)
bpy.ops.wm.save_as_mainfile(filepath=str(Path(__file__).with_name('components.blend')))
print('Component library exported:',{k:sum(len(p['positions'])//9 for p in v) for k,v in parts.items()})
