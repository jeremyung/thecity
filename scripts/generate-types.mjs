// Regenerates web/src/generated from the Rust snapshot types (ts-rs), then
// formats them. CI runs this and fails if the committed files differ.
import { spawnSync } from 'node:child_process';
import { existsSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const env = { ...process.env };
if (existsSync('.tools/cargo/bin')) {
  env.CARGO_HOME = resolve('.tools/cargo');
  env.RUSTUP_HOME = resolve('.tools/rustup');
  env.PATH = `${resolve('.tools/cargo/bin')}:${env.PATH}`;
}
function run(command, args) {
  const result = spawnSync(command, args, { env, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}
const out = 'web/src/generated';
env.TS_RS_EXPORT_DIR = resolve(out);
rmSync(out, { recursive: true, force: true });
run('cargo', [
  'test',
  '--manifest-path',
  'engine/Cargo.toml',
  '--workspace',
  '--locked',
  '--features',
  'legacy',
  '--quiet',
  'export_bindings',
]);
const names = readdirSync(out)
  .filter((file) => file.endsWith('.ts'))
  .map((file) => file.slice(0, -3))
  .sort();
writeFileSync(
  `${out}/index.ts`,
  '// Generated by scripts/generate-types.mjs from the Rust snapshot types. Do not edit.\n' +
    names
      .map((name) =>
        name === 'wire'
          ? `export * from './wire';\n`
          : `export type { ${name} } from './${name}';\n`,
      )
      .join(''),
);
run('npx', ['prettier', '--write', '--log-level', 'warn', out]);
