// Reproducible Blender -> triangle library -> validated manifest. No generation services.
import {readFile,writeFile,access} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
const source='art-workshop/architecture-pilot/runtime-components/build.py';
const generated='web/src/render/generated/apartment-components.ts';
const manifestPath='public/art/apartment-pilot/manifest.json';
const check=process.argv.includes('--check'),manifestOnly=process.argv.includes('--manifest-only');
if(!check&&!manifestOnly){
 let blender=process.env.BLENDER_BIN;
 if(!blender){try{await access('/Applications/Blender.app/Contents/MacOS/Blender');blender='/Applications/Blender.app/Contents/MacOS/Blender';}catch{blender='blender';}}
 const result=spawnSync(blender,['--background','--factory-startup','--python',fileURLToPath(new URL(source,root))],{cwd:fileURLToPath(root),stdio:'inherit'});
 if(result.error)throw result.error;if(result.status!==0)throw new Error(`Blender exit ${result.status}`);
}
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const bytes=await readFile(new URL(generated,root)),text=bytes.toString();
const start=text.indexOf('export const apartmentComponents = ')+34;
if(start<34)throw new Error('Missing component export');
const data=JSON.parse(text.slice(start,text.lastIndexOf(' as const;')));
const components={};
for(const [name,parts] of Object.entries(data)){
 let triangles=0;const min=[Infinity,Infinity,Infinity],max=[-Infinity,-Infinity,-Infinity];
 for(const part of parts){
  const p=part.positions,n=part.normals,uv=part.uvs;
  if(!['metal','concrete','glass'].includes(part.material)||!p.length||p.length%9||n.length!==p.length||uv.length!==p.length/3*2||![...p,...n,...uv].every(Number.isFinite))throw new Error(`Invalid ${name} geometry`);
  triangles+=p.length/9;
  p.forEach((v,i)=>{min[i%3]=Math.min(min[i%3],v);max[i%3]=Math.max(max[i%3],v);});
 }
 components[name]={triangles,materialRoles:[...new Set(parts.map(p=>p.material))].sort(),boundsMeters:{min,max},attachment:'local origin; +Z is outward'};
}
const textures={};
const textureNames=['warm-plaster','cast-concrete','old-mineral-plaster','old-sand-coat','old-concrete','old-brown-ceramic','old-taupe-ceramic','new-ivory-porcelain','new-honed-limestone','new-white-precast','new-bronze-metal','new-charcoal-ceramic'];
for(const name of textureNames){
 const path=`public/art/apartment-pilot/${name}.png`,b=await readFile(new URL(path,root));
 const width=b.readUInt32BE(16),height=b.readUInt32BE(20);
 const expectedSide=['warm-plaster','cast-concrete'].includes(name)?512:256;
 if(width!==expectedSide||height!==expectedSide)throw new Error(`Unexpected texture size for ${name}`);
 textures[name]={path,sha256:hash(b),width,height,repeatMeters:.4,colorSpace:'sRGB'};
}
const textureModule='web/src/render/generated/apartment-textures.ts';
const textureSource='// Generated by build-architecture-assets.mjs; content hashes invalidate stale CDN/browser assets.\nexport const apartmentTextureVersions = '+JSON.stringify(Object.fromEntries(Object.entries(textures).map(([name,entry])=>[name,entry.sha256.slice(0,16)])),null,2)+' as const;\n';
if(check){if(await readFile(new URL(textureModule,root),'utf8')!==textureSource)throw new Error('Architecture texture versions stale');}
else await writeFile(new URL(textureModule,root),textureSource);
const manifest={schemaVersion:1,componentRevision:3,units:'metres',upAxis:'Y',source,sourceSha256:hash(await readFile(new URL(source,root))),generated,geometrySha256:hash(bytes),components,textures};
const serialized=JSON.stringify(manifest,null,2)+'\n';
if(check){if(await readFile(new URL(manifestPath,root),'utf8')!==serialized)throw new Error('Architecture manifest stale; rebuild assets');}
else await writeFile(new URL(manifestPath,root),serialized);
console.log(`${check?'Verified':'Built'} ${Object.keys(components).length} components and ${Object.keys(textures).length} textures`);
